test('tagProtector reconciles tags and line breaks accurately', () => {
  const original = '{\\an8}おはよう、アスカ！\\N今日もいい天気だね。{\\fad(200,200)}';
  const rawTranslation = 'မင်္ဂလာပါ အာဆုကာ! ဒီနေ့လည်း ရာသီဥတု သာယာတယ်နော်။';

  const reconciled = reconcileTags(original, rawTranslation);
  // Must preserve {\an8} at the start, {\fad(200,200)} at the end, and \N
  assert.ok(reconciled.startsWith('{\\an8}'), 'Should have {\\an8} prefix');
  assert.ok(reconciled.endsWith('{\\fad(200,200)}'), 'Should have {\\fad(200,200)} suffix');
  assert.ok(reconciled.includes('\\N'), 'Should have \\N line break');
});

